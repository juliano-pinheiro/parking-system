-- 6. POLÍTICAS DE ACESSO E RLS (ROW LEVEL SECURITY)
-- ==============================================================================
-- O sistema utiliza autenticação própria e controle de sessão gerenciado pelo Flask.
-- O acesso ao banco deve ocorrer somente pelo backend usando a chave service_role.
-- Nao exponha essa chave no navegador nem conceda acesso direto a anon/authenticated.

DO $$
DECLARE
    tbl text;
    tabelas_sistema text[] := ARRAY[
        'empresas', 'perfis', 'usuarios', 'permissoes', 'configuracao', 'tickets',
        'clientes', 'tipos_veiculo', 'caixas', 'movimentacoes_caixa', 'formas_pagamento',
        'tabela_precos', 'pagamentos', 'descontos', 'cortesias', 'mensalistas',
        'mensalidades', 'convenios', 'contas_receber', 'sangrias', 'suprimentos',
        'estornos', 'financeiro', 'auditoria', 'logs_acesso', 'nfse', 'lista_negra',
        'reservas', 'ocorrencias'
    ];
BEGIN
    FOREACH tbl IN ARRAY tabelas_sistema LOOP
        EXECUTE format('ALTER TABLE IF EXISTS public.%I ENABLE ROW LEVEL SECURITY;', tbl);
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated;', tbl);
        EXECUTE format('GRANT ALL ON TABLE public.%I TO service_role;', tbl);
    END LOOP;
END $$;

-- Permissões em sequences para inserções automáticas
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;


