-- Migra tabelas que ja existiam antes do suporte multiempresa. O bloco fica
-- antes dos CREATE INDEX para que esquemas antigos nao falhem em empresa_id.
DO $$
DECLARE
    tbl text;
    tabelas_empresa text[] := ARRAY[
        'usuarios', 'configuracao', 'tickets', 'clientes', 'tipos_veiculo',
        'caixas', 'movimentacoes_caixa', 'formas_pagamento', 'tabela_precos',
        'pagamentos', 'descontos', 'cortesias', 'mensalistas', 'mensalidades',
        'convenios', 'contas_receber', 'sangrias', 'suprimentos', 'estornos',
        'financeiro', 'nfse', 'lista_negra', 'reservas', 'ocorrencias'
    ];
BEGIN
    FOREACH tbl IN ARRAY tabelas_empresa LOOP
        IF to_regclass(format('public.%I', tbl)) IS NOT NULL THEN
            EXECUTE format(
                'ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS empresa_id INTEGER REFERENCES public.empresas(id)',
                tbl
            );
        END IF;
    END LOOP;

    IF to_regclass('public.usuarios') IS NOT NULL THEN
        EXECUTE
            'ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS master BOOLEAN NOT NULL DEFAULT FALSE';
    END IF;

    IF to_regclass('public.mensalistas') IS NOT NULL THEN
        EXECUTE
            'ALTER TABLE public.mensalistas ADD COLUMN IF NOT EXISTS placa TEXT';
        EXECUTE
            'ALTER TABLE public.mensalistas ADD COLUMN IF NOT EXISTS tipo_veiculo TEXT DEFAULT ''Carro''';
    END IF;
END $$;

