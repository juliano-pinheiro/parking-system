-- Bancos antigos podem ter usuarios.id como NOT NULL sem sequence/default.
-- Garante geração automatica e sincroniza o proximo valor com os IDs existentes.
DO $$
DECLARE
    seq_name text;
BEGIN
    seq_name := pg_get_serial_sequence('public.usuarios', 'id');

    IF seq_name IS NULL THEN
        CREATE SEQUENCE IF NOT EXISTS public.usuarios_id_seq;
        ALTER SEQUENCE public.usuarios_id_seq OWNED BY public.usuarios.id;
        ALTER TABLE public.usuarios
            ALTER COLUMN id SET DEFAULT nextval('public.usuarios_id_seq'::regclass);
        seq_name := 'public.usuarios_id_seq';
    END IF;

    PERFORM setval(
        seq_name::regclass,
        COALESCE((SELECT MAX(id) FROM public.usuarios), 1),
        EXISTS (SELECT 1 FROM public.usuarios)
    );
END $$;

